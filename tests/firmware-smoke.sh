grep -Fq 'clients = dhcp_clients()' "$ROOT/files/usr/lib/lua/luci/controller/quantumgrid.lua"
grep -Fq 'lease_remaining_seconds' "$ROOT/files/usr/lib/lua/luci/controller/quantumgrid.lua"
grep -Fq 'ubus_call("iwinfo", "assoclist"' "$ROOT/files/usr/lib/lua/luci/controller/quantumgrid.lua"
