    grep -qx "CONFIG_PACKAGE_${package}=y" "$CONFIG"
done

grep -Fq 'setup-aw1000-phone-feed.sh' "$ROOT/build.sh"
grep -Fq 'scripts/build-ui.sh' "$ROOT/build.sh"
grep -Fq 'npm ci --no-audit --no-fund' "$ROOT/scripts/build-ui.sh"
